#if defined(_WIN32)
#include <windows.h>
static void trivi_sleep_ms(unsigned ms) { Sleep(ms); }
#else
#include <time.h>
static void trivi_sleep_ms(unsigned ms)
{
    struct timespec ts;
    ts.tv_sec = (time_t)(ms / 1000u);
    ts.tv_nsec = (long)(ms % 1000u) * 1000000L;
    nanosleep(&ts, NULL);
}
#endif

