#define TRIVI_SAFFRON "\033[38;5;208m"
#define TRIVI_GREEN "\033[32m"
#define TRIVI_BOLD "\033[1m"
#define TRIVI_DIM "\033[2m"
#define TRIVI_RESET "\033[0m"

static void trivi_draw(int f, int color)
{
    int r;
    for (r = 0; r < TRIVI_ART_ROWS; ++r)
        printf("%s%s%s\033[K\n", color ? TRIVI_SAFFRON : "", trivi_frames[f][r],
               color ? TRIVI_RESET : "");
    printf("%s~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~%s\033[K\n",
           color ? TRIVI_GREEN : "", color ? TRIVI_RESET : "");
    printf(" %s%s%s\033[K\n", color ? (f == TRIVI_FRAMES - 1 ? TRIVI_BOLD : TRIVI_DIM) : "",
           trivi_frames[f][TRIVI_ART_ROWS], color ? TRIVI_RESET : "");
    fflush(stdout);
}

static void trivi_story(int animate)
{
    static const unsigned hold_ms[TRIVI_FRAMES] = {1100, 800, 900, 900, 0};
    int f;
    if (!animate) {
        int r;
        for (r = 0; r < TRIVI_ART_ROWS; ++r) printf("%s\n", trivi_frames[TRIVI_FRAMES - 1][r]);
        printf("~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~\n %s\n",
               trivi_frames[TRIVI_FRAMES - 1][TRIVI_ART_ROWS]);
        return;
    }
    printf("\033[?25l"); /* hide the cursor */
    for (f = 0; f < TRIVI_FRAMES; ++f) {
        if (f) printf("\033[%dA", TRIVI_ART_ROWS + 2); /* back to the top of the picture */
        trivi_draw(f, 1);
        trivi_sleep_ms(hold_ms[f]);
    }
    printf("\033[?25h\n");
    fflush(stdout);
}

static void trivi_picture(int animate, int columns)
{
    static const char title[] = "T R I V I K R A M A";
    static const char motto[] = "a tiny chip, a giant model";
    const char *const *pic = columns >= 120 ? trivi_picture_wide : trivi_picture_narrow;
    int rows = columns >= 120 ? (int)(sizeof trivi_picture_wide / sizeof *pic)
                              : (int)(sizeof trivi_picture_narrow / sizeof *pic);
    int width = columns >= 120 ? 120 : 60, pad, r;
    const char *c;
    if (!animate) {
        printf("%s   %s\n", title, motto);
        return;
    }
    printf("\033[?25l");
    for (r = 0; r < rows; ++r) { /* reveal top to bottom */
        printf(TRIVI_GREEN "\033[1m%s" TRIVI_RESET "\n", pic[r]);
        fflush(stdout);
        trivi_sleep_ms(columns >= 120 ? 12 : 25);
    }
    pad = (width - (int)(sizeof title - 1)) / 2;
    printf("\n%*s" TRIVI_SAFFRON TRIVI_BOLD, pad, "");
    for (c = title; *c; ++c) { /* type the name */
        putchar(*c);
        fflush(stdout);
        trivi_sleep_ms(*c == ' ' ? 30 : 90);
    }
    pad = (width - (int)(sizeof motto - 1)) / 2;
    printf(TRIVI_RESET "\n%*s" TRIVI_DIM "%s" TRIVI_RESET "\n\n", pad, "", motto);
    printf("\033[?25h");
    fflush(stdout);
}

/*
 * style    1: the picture, 2: the story animation
 * animate  0 prints one plain line instead (logs, pipes, tests)
 * columns  terminal width; 120 or more shows the full-size picture
 */
static void trivi_banner(int style, int animate, int columns)
{
    if (style == 2) trivi_story(animate);
    else trivi_picture(animate, columns);
}

